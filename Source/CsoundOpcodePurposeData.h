/**
    Seconda tabella di help, piu' ampia ma "piu' leggera" di
    CsoundOpcodeHelpData::table: una riga di descrizione per opcode,
    trascritta dalla riga "refpurpose" del Csound Reference Manual
    (csound.com/docs/manual/PartReference.html, l'indice alfabetico
    completo di opcode e operatori - lo stesso testo che CsoundQt mostra
    come help rapido, preso dal manuale che lui ha in locale).

    A differenza di CsoundOpcodeHelpData::table (sintassi completa + prosa,
    verificata pagina per pagina, ma solo per gli opcode piu' comuni), qui
    non c'e' la riga di sintassi "umana" - quella, per questi opcode, resta
    la firma di tipo grezza letta dal motore (vedi
    CsoundCodeEditor::pushSignatureHelp). Questa tabella copre solo gli
    operatori/simboli e gli opcode le cui iniziali vanno dai simboli fino
    alla lettera L compresa (il fetch in blocco dell'indice del manuale si
    interrompe per limite di dimensione intorno alla lettera O, ma per
    restare su descrizioni rilette e controllate ci si e' fermati a L);
    sono stati esclusi di proposito i gruppi di opcode molto di nicchia
    (widget FLTK "FL*", integrazione Jack "Jacko*"/"jacktransport",
    analisi/risintesi ATS "ATS*", Ableton Link "link_*", lettura/scrittura
    HDF5, orchestra remota "insremot"/"insglobal", gestione immagini
    "image*") perche' sono centinaia di opcode molto specialistici che
    raramente si digitano esplorando l'autocompletamento. Per TUTTI gli
    opcode non presenti ne' qui ne' in CsoundOpcodeHelpData, l'help mostra
    comunque la firma di tipo grezza (sempre corretta, letta dal motore),
    semplicemente senza una riga di descrizione in prosa - ampliare questa
    tabella (o quella in CsoundOpcodeHelpData) resta il modo naturale per
    aggiungere altre descrizioni in futuro.
*/
