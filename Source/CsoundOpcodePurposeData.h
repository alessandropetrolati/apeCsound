    inline const char* find (const juce::String& opcodeName)
    {
        const auto trimmed = opcodeName.trim();

        if (trimmed.isEmpty())
            return nullptr;

        for (auto& entry : table)
            if (trimmed.equalsIgnoreCase (entry.name))
                return entry.purpose;

        return nullptr;
    }
